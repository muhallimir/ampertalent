/**
 * Demo Seeding — Pure data builders
 *
 * Builders for the sample data a fresh demo account ships with. They are
 * deliberately PURE (no DB) so they can be unit-tested in isolation. The API
 * route `app/api/demo/seed/route.ts` calls these builders and writes the
 * results to the DB.
 *
 * Naming convention: every demo job title contains "Demo" so a quick
 * `db.job.findMany({ where: { title: { contains: 'Demo' } } })` finds them for
 * dashboard filtering and Playwright assertions.
 *
 * Field names mirror the Prisma schema:
 *  - Job.employerId (FK to Employer.userId)
 *  - Job.type (JobType enum, UPPERCASE)
 *  - Job.category (JobCategory enum, UPPERCASE)
 *  - Job.status (JobStatus enum, lowercase: 'approved' for live listings)
 *  - Application.seekerId (FK to JobSeeker.userId)
 *  - Application.resumeUrl (required)
 */

import type { JobType, JobCategory, JobStatus, ApplicationStatus } from '@prisma/client'

