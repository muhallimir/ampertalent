/* Sample applications                                                        */
/* -------------------------------------------------------------------------- */

export interface SampleApplication {
  seekerId: string
  jobId: string
  status: ApplicationStatus
  resumeUrl: string
  coverLetter: string | null
}

export function buildSampleApplications({
  seekerProfileId,
  jobs,
  max = 3,
}: {
  seekerProfileId: string
  jobs: Array<{ id: string; title?: string }>
  max?: number
}): SampleApplication[] {
  const capped = Math.min(max, jobs.length)
  return jobs.slice(0, capped).map((job, idx) => ({
    seekerId: seekerProfileId,
    jobId: job.id,
    status: 'pending' as ApplicationStatus,
    resumeUrl: `https://ampertalent-demo.com/resumes/${seekerProfileId}-${idx}.pdf`,
    coverLetter:
      idx === 0
        ? 'Hi! I saw the demo job posting and I am very interested. I have shipped similar features before and would love to chat.'
        : null,
  }))
}
