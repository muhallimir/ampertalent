export interface SampleJob {
  title: string
  description: string
  locationText: string
  category: JobCategory
  type: JobType
  status: JobStatus
  employerId: string
  skillsRequired: string[]
  payRangeText: string | null
}

export function buildSampleJobs({
  employerProfileId,
  count = 3,
}: {
  employerProfileId: string
  count?: number
}): SampleJob[] {
  const safeCount = Math.max(1, Math.min(count, SAMPLE_JOB_TEMPLATES.length))
  const out: SampleJob[] = []
  // Pick `safeCount` distinct templates so the same visitor gets fresh jobs each
  // time. We shuffle a copy of the templates array.
  const indices = Array.from({ length: SAMPLE_JOB_TEMPLATES.length }, (_, i) => i)
  for (let i = indices.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1))
    ;[indices[i], indices[j]] = [indices[j], indices[i]]
  }
  for (let i = 0; i < safeCount; i++) {
    const tpl = SAMPLE_JOB_TEMPLATES[indices[i]]
    out.push({
      title: tpl.title,
      description: tpl.description,
      locationText: tpl.locationText,
      category: tpl.category,
      type: tpl.type,
      status: 'approved',
      employerId: employerProfileId,
      skillsRequired: ['Communication', 'Remote Collaboration', 'TypeScript'],
      payRangeText: i === 0 ? '$90k - $130k' : i === 1 ? '$70k - $100k' : '$50k - $80k',
    })
  }
  return out
}

